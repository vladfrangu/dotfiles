#!/usr/bin/env python3
"""Generate LiteLLM ChatGPT routes from Codex's authenticated model catalog."""

from __future__ import annotations

import argparse
import json
import os
import re
import select
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent
CONFIG_PATH = ROOT / "litellm-config.yaml"
SAFE_MODEL = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


class AppServerError(RuntimeError):
    pass


def send(process: subprocess.Popen[str], message: dict[str, Any]) -> None:
    assert process.stdin is not None
    process.stdin.write(json.dumps(message, separators=(",", ":")) + "\n")
    process.stdin.flush()


def response_for(
    process: subprocess.Popen[str], request_id: int, timeout: float = 20
) -> dict[str, Any]:
    assert process.stdout is not None
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        ready, _, _ = select.select([process.stdout], [], [], max(0, deadline - time.monotonic()))
        if not ready:
            break
        line = process.stdout.readline()
        if not line:
            assert process.stderr is not None
            details = process.stderr.read().strip()
            if details:
                raise AppServerError(f"Codex app-server exited before responding: {details}")
            break
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            continue
        if message.get("id") == request_id:
            if "error" in message:
                raise AppServerError(str(message["error"]))
            return message["result"]
    raise AppServerError(f"Timed out waiting for Codex app-server request {request_id}")


def discover_models() -> list[str]:
    try:
        process = subprocess.Popen(
            ["codex", "app-server", "--stdio"],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
        )
    except FileNotFoundError as exc:
        raise AppServerError("Codex CLI is not installed or not on PATH") from exc

    try:
        send(
            process,
            {
                "method": "initialize",
                "id": 1,
                "params": {
                    "clientInfo": {"name": "claude-codex-model-sync", "version": "0.1.0"},
                    "capabilities": None,
                },
            },
        )
        response_for(process, 1)
        send(process, {"method": "initialized", "params": {}})
        send(
            process,
            {
                "method": "model/list",
                "id": 2,
                "params": {"includeHidden": False, "limit": 100},
            },
        )
        result = response_for(process, 2)
    finally:
        process.terminate()
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()

    models: list[str] = []
    for item in result.get("data", []):
        model = item.get("model")
        if isinstance(model, str) and SAFE_MODEL.fullmatch(model) and model not in models:
            models.append(model)
    if not models:
        raise AppServerError("Codex returned no visible models; leaving the config unchanged")
    return models


def render_config(models: list[str]) -> str:
    lines = [
        "# Generated by sync_models.py from Codex's authenticated model/list catalog.",
        "# Run: claude-codex models-sync",
        "model_list:",
    ]
    for model in models:
        lines.extend(
            [
                f"  - model_name: {model}",
                "    model_info:",
                "      mode: responses",
                "    litellm_params:",
                f"      model: chatgpt/{model}",
                "      supports_system_message: false",
                "",
            ]
        )
    lines.extend(
        [
            "litellm_settings:",
            "  master_key: os.environ/LITELLM_MASTER_KEY",
            "  drop_params: true",
            "",
        ]
    )
    return "\n".join(lines)


def write_config(content: str) -> None:
    fd, temporary_name = tempfile.mkstemp(prefix=".litellm-config-", dir=ROOT, text=True)
    try:
        with os.fdopen(fd, "w") as temporary:
            temporary.write(content)
        os.replace(temporary_name, CONFIG_PATH)
    except BaseException:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass
        raise


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--list", action="store_true", help="print discovered model names")
    group.add_argument("--dry-run", action="store_true", help="print the generated YAML")
    args = parser.parse_args()

    try:
        models = discover_models()
    except AppServerError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    if args.list:
        print("\n".join(models))
    elif args.dry_run:
        print(render_config(models), end="")
    else:
        write_config(render_config(models))
        print(f"Updated {CONFIG_PATH} with {len(models)} visible Codex models:")
        print("\n".join(f"  {model}" for model in models))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
